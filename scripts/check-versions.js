#!/usr/bin/env node
/**
 * Release-manifest consistency check.
 *
 * Three files must agree, and each disagreement fails in a different place:
 *
 *   package.json   the source of truth; what bumpp reads and writes
 *   manifest.json  what Zotero enforces when the plugin is installed
 *   update.json    what Zotero fetches to decide whether an update EXISTS and
 *                  is compatible, and where to download it from
 *
 * A mismatch here does not fail on this machine. It fails on a user's machine,
 * after a release: a stale update.json version means the update is never
 * offered, a stale strict_max_version means users on a newer Zotero stay
 * disabled forever without ever receiving the fixed build, and an update_link
 * that does not match the uploaded asset name is a 404 mid-update.
 *
 * Both of these have happened here: package.json drifting behind manifest.json
 * turned a patch bump into an apparent downgrade, and release.js hardcoded the
 * version gate so it would silently rewrite update.json back to an old value.
 *
 *   npm run check:versions
 */

const fs = require('fs');
const path = require('path');

const rootDir = path.resolve(__dirname, '..');
const read = (f) => JSON.parse(fs.readFileSync(path.resolve(rootDir, f), 'utf8'));

const pkg = read('package.json');
const manifest = read('manifest.json');
const update = read('update.json');

const problems = [];
const pluginId = manifest.applications?.zotero?.id;
const manifestApp = manifest.applications?.zotero || {};

const entries = update.addons?.[pluginId]?.updates;
if (!Array.isArray(entries) || entries.length === 0) {
  problems.push(`update.json has no updates entry for "${pluginId}"`);
}
const entry = entries?.[0] || {};
const app = entry.applications?.zotero || {};

if (pkg.version !== manifest.version) {
  problems.push(`package.json is ${pkg.version} but manifest.json is ${manifest.version}`);
}
if (entry.version && pkg.version !== entry.version) {
  problems.push(`package.json is ${pkg.version} but update.json advertises ${entry.version}`);
}

for (const key of ['strict_min_version', 'strict_max_version']) {
  if (manifestApp[key] !== app[key]) {
    problems.push(`${key}: manifest.json says ${manifestApp[key]}, update.json says ${app[key]}`);
  }
}

// The gate must never reach beyond the major it was tested against. Zotero asks
// plugin authors not to exceed the major version, and values like "99.*" used
// to dodge testing are explicitly disallowed.
const max = manifestApp.strict_max_version;
if (max && !/^\d+\.(\d+\.)?\*$/.test(String(max))) {
  problems.push(`strict_max_version "${max}" is not of the form N.* or N.M.*`);
}

// The download URL must name the asset that the release actually uploads,
// which release.js builds as zotseek-<version>.xpi under tag v<version>.
const expectedSuffix = `/releases/download/v${pkg.version}/zotseek-${pkg.version}.xpi`;
if (entry.update_link && !String(entry.update_link).endsWith(expectedSuffix)) {
  problems.push(`update_link does not point at the v${pkg.version} asset:\n      ${entry.update_link}`);
}

if (problems.length > 0) {
  console.error('Release manifests disagree:\n');
  for (const p of problems) console.error(`  - ${p}`);
  console.error('\nupdate.json is generated by scripts/release.js from package.json and');
  console.error('manifest.json; do not edit it by hand. Re-run the release script, or set');
  console.error('package.json to the intended version first since it is the source of truth.\n');
  process.exit(1);
}

console.log(`Release manifests agree: v${pkg.version}, Zotero ${manifestApp.strict_min_version} to ${manifestApp.strict_max_version}.`);
